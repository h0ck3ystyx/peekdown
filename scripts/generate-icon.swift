import AppKit

let ink = NSColor(srgbRed: 15/255, green: 23/255, blue: 38/255, alpha: 1)
let yellow = NSColor(srgbRed: 1, green: 216/255, blue: 77/255, alpha: 1)
let output = URL(fileURLWithPath: CommandLine.arguments[1], isDirectory: true)
try FileManager.default.createDirectory(at: output, withIntermediateDirectories: true)

// Coordinates use the same top-left, 64-unit grid as the landing-page mark.
let eye = NSBezierPath()
eye.move(to: NSPoint(x: 9, y: 32))
eye.curve(to: NSPoint(x: 55, y: 32), controlPoint1: NSPoint(x: 19.5, y: 16), controlPoint2: NSPoint(x: 44.5, y: 16))
eye.curve(to: NSPoint(x: 9, y: 32), controlPoint1: NSPoint(x: 44.5, y: 48), controlPoint2: NSPoint(x: 19.5, y: 48))
eye.close()
let arrow = NSBezierPath()
arrow.move(to: NSPoint(x: 32, y: 26.4))
arrow.line(to: NSPoint(x: 32, y: 36.8))
arrow.move(to: NSPoint(x: 27.6, y: 32.4))
arrow.line(to: NSPoint(x: 32, y: 36.8))
arrow.line(to: NSPoint(x: 36.4, y: 32.4))

func svgPath(_ path: NSBezierPath) -> String {
    var commands: [String] = []
    let points = UnsafeMutablePointer<NSPoint>.allocate(capacity: 3)
    defer { points.deallocate() }
    func pair(_ point: NSPoint) -> String { "\(point.x) \(point.y)" }
    for i in 0..<path.elementCount {
        switch path.element(at: i, associatedPoints: points) {
        case .moveTo: commands.append("M" + pair(points[0]))
        case .lineTo: commands.append("L" + pair(points[0]))
        case .curveTo, .cubicCurveTo: commands.append("C" + pair(points[0]) + " " + pair(points[1]) + " " + pair(points[2]))
        case .quadraticCurveTo: commands.append("Q" + pair(points[0]) + " " + pair(points[1]))
        case .closePath: commands.append("Z")
        @unknown default: fatalError("Unsupported path element")
        }
    }
    return commands.joined(separator: " ")
}
let svg = """
<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 64 64">
  <title>Peekdown app icon</title>
  <!-- Generated by scripts/generate-icon.swift. Copyright 2026 Chuck Sinnett. MIT. -->
  <g transform="translate(6 6) scale(0.8125)">
    <rect width="64" height="64" rx="15" fill="#0F1726"/>
    <path d="\(svgPath(eye))" fill="none" stroke="#fff" stroke-width="4.6" stroke-linejoin="round"/>
    <circle cx="32" cy="32" r="9.6" fill="#FFD84D"/>
    <path d="\(svgPath(arrow))" fill="none" stroke="#0F1726" stroke-width="3" stroke-linecap="round" stroke-linejoin="round"/>
  </g>
</svg>
"""
try svg.write(to: URL(fileURLWithPath: "Artwork/Peekdown.svg"), atomically: true, encoding: .utf8)

for size in [16, 32, 128, 256, 512] {
    for scale in [1, 2] {
        let pixels = size * scale
        let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: pixels, pixelsHigh: pixels,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0)!
        bitmap.size = NSSize(width: pixels, height: pixels)
        NSGraphicsContext.saveGraphicsState()
        NSGraphicsContext.current = NSGraphicsContext(bitmapImageRep: bitmap)
        let transform = NSAffineTransform()
        transform.translateX(by: 0, yBy: CGFloat(pixels))
        transform.scaleX(by: CGFloat(pixels)/64, yBy: -CGFloat(pixels)/64)
        transform.concat()
        let inset = NSAffineTransform()
        inset.translateX(by: 6, yBy: 6)
        inset.scale(by: 0.8125)
        inset.concat()
        ink.setFill()
        NSBezierPath(roundedRect: NSRect(x: 0, y: 0, width: 64, height: 64), xRadius: 15, yRadius: 15).fill()
        NSColor.white.setStroke()
        eye.lineWidth = 4.6
        eye.lineJoinStyle = .round
        eye.stroke()
        yellow.setFill()
        // Slightly larger pupil and arrow stroke keep the mark legible at 16/32 pt.
        let radius: CGFloat = size <= 32 ? 10.4 : 9.6
        NSBezierPath(ovalIn: NSRect(x: 32-radius, y: 32-radius, width: radius*2, height: radius*2)).fill()
        ink.setStroke()
        arrow.lineWidth = size <= 32 ? 3.4 : 3
        arrow.lineCapStyle = .round
        arrow.lineJoinStyle = .round
        arrow.stroke()
        NSGraphicsContext.restoreGraphicsState()
        let suffix = scale == 2 ? "@2x" : ""
        let filename = "icon_\(size)x\(size)\(suffix).png"
        try bitmap.representation(using: .png, properties: [:])!.write(to: output.appendingPathComponent(filename))
    }
}
